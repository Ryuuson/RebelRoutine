// Production split controller handlers; only SDK boundaries are substituted.
const assert = require('assert/strict');
const {subject,context} = require('./load_07_handlers.cjs');
module.exports={subject,context};
(async()=>{
  const app=subject();
  app.chooseTrait('draft', 'kindness', ['auto']);
  assert.equal(app.draftTraits.join(','), 'kindness');
  app.chooseTrait('draft', 'health', app.draftTraits);
  assert.equal(app.draftTraits.join(','), 'kindness,health');
  app.chooseTrait('draft', 'none', app.draftTraits);
  assert.equal(app.assignedSelection(app.draftTraits).length, 0);
  app.chooseTrait('draft', 'auto', app.draftTraits);
  assert.equal(app.assignedSelection(app.draftTraits), undefined);
  await app.addTask('完全不含关键词的自定义活动', '', ['kindness','kindness','health','bad']);
  const id=app.habits[0].id;
  await app.toggleHabit(id);
  assert.equal(app.traitScore('kindness'),1); assert.equal(app.traitScore('health'),1);
  assert.equal(app.traitScore('knowledge'),0);
  app.startEditing(app.habits[0]); app.editTraits=['proficiency']; await app.saveEditing();
  assert.equal(app.traitScore('kindness'),0); assert.equal(app.traitScore('health'),0);
  assert.equal(app.traitScore('proficiency'),1);
  await app.toggleHabit(id); assert.equal(app.traitScore('proficiency'),0);
  assert.equal(app.habits[0].assignedTraits.join(','),'proficiency');
  await app.toggleHabit(id); assert.equal(app.traitScore('proficiency'),1);
  app.startNewPinned(); app.pinnedEditTitle=app.habits[0].title; app.pinnedEditSubtitle=app.habits[0].subtitle; app.pinnedEditTraits=[...app.habits[0].assignedTraits]; app.pinnedEditPoints=[...app.habits[0].assignedPoints??[]]; await app.savePinnedEditing();
  assert.equal(app.pinnedTasks[0].assignedTraits.join(','),'proficiency');
  app.startPinnedEditing(app.pinnedTasks[0]); app.pinnedEditTraits=['charm']; await app.savePinnedEditing();
  assert.equal(app.pinnedTasks[0].assignedTraits.join(','),'charm');
  app.habits[0].day='2026-09-29'; await app.reuseYesterday();
  assert.equal(app.todayHabits()[0].assignedTraits.join(','),'proficiency');
  assert.equal(app.todayHabits()[0].done,false);
  await app.addTask('明确不计点','',[]); const none=app.habits.at(-1);
  await app.toggleHabit(none.id); assert.equal(none.assignedTraits.length,0);
  assert.equal(app.habits.at(-1).awardedTraits.length,0);
  const persisted=JSON.parse(JSON.stringify(app.habits));
  assert.equal(persisted.at(-1).assignedTraits.length,0);
  await app.addTask('自动识别'); await app.toggleHabit(app.habits.at(-1).id);
  assert.equal(app.traitScore('knowledge'),1);
  await app.lifecycle(app.habits.at(-1).id,'delete'); await app.confirmOperation(); assert.equal(app.traitScore('knowledge'),0);
  const pointsApp=subject();
  await pointsApp.addTask('自定多维点数','',['knowledge','health'],[{key:'knowledge',points:3},{key:'health',points:2}]);
  const pointId=pointsApp.habits[0].id;
  await pointsApp.toggleHabit(pointId);
  assert.equal(pointsApp.traitScore('knowledge'),3);
  assert.equal(pointsApp.traitScore('health'),2);
  await pointsApp.toggleHabit(pointId);
  assert.equal(pointsApp.traitScore('knowledge'),0);
  assert.equal(pointsApp.traitScore('health'),0);
  await pointsApp.toggleHabit(pointId);
  pointsApp.startEditing(pointsApp.habits[0]);
  pointsApp.setPoints('habit','knowledge','7'); await pointsApp.saveEditing();
  assert.equal(pointsApp.traitScore('knowledge'),7);
  assert.equal(pointsApp.traitScore('health'),2);
  pointsApp.startNewPinned(); pointsApp.pinnedEditTitle=pointsApp.habits[0].title; pointsApp.pinnedEditSubtitle=pointsApp.habits[0].subtitle; pointsApp.pinnedEditTraits=[...pointsApp.habits[0].assignedTraits]; pointsApp.pinnedEditPoints=[...pointsApp.habits[0].assignedPoints??[]]; await pointsApp.savePinnedEditing();
  assert.equal(pointsApp.pinnedTasks[0].assignedPoints.find(p=>p.key==='knowledge').points,7);
  pointsApp.habits[0].day='2026-09-29'; await pointsApp.reuseYesterday();
  assert.equal(pointsApp.todayHabits()[0].assignedPoints.find(p=>p.key==='knowledge').points,7);
  pointsApp.habits[0].day='2026-09-30'; await pointsApp.lifecycle(pointId,'delete'); await pointsApp.confirmOperation();
  assert.equal(pointsApp.traitScore('knowledge'),0);
  assert.equal(pointsApp.traitScore('health'),0);
  const recordApp=subject();
  await recordApp.addTask('昨天已经做完的事情','',['kindness'],[{key:'kindness',points:4}],'2026-09-29',true);
  assert.equal(recordApp.habits[0].activityDay,'2026-09-29');
  assert.equal(recordApp.habits[0].day,undefined);
  assert.ok(recordApp.habits[0].createdAt >= Date.now()-1000);
  assert.equal(recordApp.traitScore('kindness'),4);
  const beforeFailure=JSON.stringify(recordApp.snapshot());
  recordApp.store.saveSnapshot=async()=>{throw Error('disk unavailable')};
  assert.equal(await recordApp.addTask('不应出现在界面的保存失败任务'),false);
  assert.equal(JSON.stringify(recordApp.snapshot()),beforeFailure);
  assert.ok(recordApp.notice.includes('disk unavailable'));
  const priorRecord=subject();
  await priorRecord.addTask('跨日事项','','kindness'.split(','),[], '2026-09-29');
  const priorId=priorRecord.habits[0].id;
  await priorRecord.toggleHabit(priorId);
  assert.equal(priorRecord.habits[0].day,'2026-09-29');
  assert.equal(priorRecord.habits[0].activityDay,'2026-09-30');
  console.log('PASS: manual selection, completed edit, undo/redo, pin/edit, reuse, no points, persistence, auto and deletion');
})().catch(error=>{console.error(error); process.exitCode=1;});



